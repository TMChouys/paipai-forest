def run(code, inputs):
    feed = list(inputs)
    buf = io.StringIO()
    old_input = builtins.input

    def fake_input(prompt=""):
        v = feed.pop(0)
        buf.write(str(prompt) + v + "\n")
        return v
    builtins.input = fake_input
    cwd = os.getcwd()
    tmp = os.path.join(ROOT, ".godot", "lesson_tmp")
    os.makedirs(tmp, exist_ok=True)
    os.chdir(tmp)
    try:
        with contextlib.redirect_stdout(buf):
            exec(compile(code, "<lesson>", "exec"), {"__name__": "__main__"})
    finally:
        builtins.input = old_input
        os.chdir(cwd)
    return buf.getvalue().rstrip("\n")


def main():
    km = json.load(open(os.path.join(ROOT, "data", "curriculum", "knowledge_map.json"), encoding="utf-8"))
    ids = [c["id"] for c in km["concepts"]] + [c["id"] for c in EXTRA_CONCEPTS]
    missing = [i for i in ids if i not in LESSONS]
    extra = [i for i in LESSONS if i not in ids]
    assert not missing and not extra, (missing, extra)
    out = {}
    for cid, les in LESSONS.items():
        les = dict(les)
        if les["output"] is None:
            les["output"] = run(les["code"], les["inputs"])
        q = dict(les["quiz"])
        assert 0 <= q["answer"] < len(q["options"]), cid
        les["why"] = WHY.get(cid, "")
        rq = QUIZ.get(cid, {})
        q.update(rq.get("main", {}))
        les["quiz"] = q
        les["quiz_more"] = rq.get("more", [])
        for qq in [q] + les["quiz_more"]:
            assert 0 <= qq["answer"] < len(qq["options"]), cid
            assert len(qq.get("wrong", qq["options"])) == len(qq["options"]), cid
            assert qq.get("wrong", [""] * 9)[qq["answer"]] == "", cid
        ch = les["ch"].split(".")[0].split("–")[0]
        les["chapter"] = CHAPTERS.get(ch, "補充")
        out[cid] = les
    data = {
        "schema": 1,
        "note": "派派兔的森林小課（原慢慢館長的課；tools/curriculum/gen_lessons.py 產生，不要手改）。章節照《Python零基礎入門班（第五版）》，說明和範例是派派森林版。",
        "book": "Python零基礎入門班（第五版）",
        "extra_concepts": EXTRA_CONCEPTS,
        "lessons": out,
    }
    json.dump(data, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("lessons:", len(out), "→", OUT)


if __name__ == "__main__":
    main()
